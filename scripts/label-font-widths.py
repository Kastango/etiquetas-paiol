"""Glyph widths of the label fonts, so the label PDF can fit names before react-pdf lays them out.

uv run --with fonttools scripts/label-font-widths.py

Writes src/lib/label-widths.ts: advance widths in em/1000 of Poppins 500, 700 and 800 for the
characters a product name can use (Latin-1 plus typographic quotes and dashes).
"""
import json
from pathlib import Path
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
chars = "".join(chr(c) for c in [*range(32, 127), *range(160, 256)]) + "‘’“”–—•…€"
widths = {}
for weight in (500, 700, 800):
    font = TTFont(root / f"public/fonts/Poppins-{weight}.ttf")
    cmap, metrics, scale = font.getBestCmap(), font["hmtx"].metrics, 1000 / font["head"].unitsPerEm
    widths[weight] = [round(metrics[cmap[ord(c)]][0] * scale) if ord(c) in cmap else 600 for c in chars]

lines = [f"  {weight}: {json.dumps(values, separators=(',', ':'))}," for weight, values in widths.items()]
(root / "src/lib/label-widths.ts").write_text(
    "// Generated by scripts/label-font-widths.py: Poppins advance widths in em/1000, one per character of CHARS.\n"
    f"export const CHARS = {json.dumps(chars, ensure_ascii=False)};\n"
    "export const WIDTHS: Record<500 | 700 | 800, number[]> = {\n" + "\n".join(lines) + "\n};\n")
print("Wrote src/lib/label-widths.ts")
